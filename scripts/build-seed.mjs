// Generates migrations/0002_seed.sql from the prototype's own seed() so the live system starts with
// exactly the demo data the business already reviewed.
//
//   node scripts/build-seed.mjs                 → demo seed (all prototype data)
//   node scripts/build-seed.mjs --masters-only  → branches, programmes, fees, discounts, staff, settings only
//
// Demo staff log in with their e-mail and DEMO_PASSWORD (default below) and must change it on first login.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { pbkdf2Sync, randomBytes } from 'node:crypto';
import { COLLECTIONS, SETTINGS_KEYS, indexFor, ID_FORMAT } from '../src/lib/indexing.ts';

const root = new URL('..', import.meta.url);
const mastersOnly = process.argv.includes('--masters-only');
const DEMO_PASSWORD = process.env.DEMO_PASSWORD || 'Welcome@LOF2026';
const PBKDF2_ITER = 100000; // Workers WebCrypto maximum

export function extractPrototypeScript(html) {
  const m = html.match(/<script>\n'use strict';([\s\S]*?)<\/script>/);
  if (!m) throw new Error('Prototype <script> block not found');
  return "'use strict';" + m[1];
}

export function runPrototypeSeed(html) {
  const code = extractPrototypeScript(html).replace(/\nboot\(\);\s*$/, '\n');
  const noop = () => {};
  const el = { addEventListener: noop, querySelector: () => null, querySelectorAll: () => [], dataset: {}, removeAttribute: noop };
  const ctx = vm.createContext({
    console, Intl, Date, Math, JSON, Object, Array, String, Number, Boolean, RegExp, Error, Map, Set, Promise,
    parseInt, parseFloat, isNaN, setTimeout, clearTimeout,
    document: { ...el, documentElement: el, activeElement: null, createElement: () => el },
    navigator: {}, matchMedia: () => ({ matches: false }), innerWidth: 1280,
  });
  vm.runInContext(code + '\n;globalThis.__seed = seed;', ctx, { filename: 'prototype.js' });
  // Sample data must not carry the prototype's "(simulated …)" wording: the screens strip it, and history would then look rewritten
  return JSON.parse(JSON.stringify(ctx.__seed()).replace(/\s?\((?:simulated|Simulated)[^)"]*\)/g, ''));
}

const q = (v) => (v == null ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'");

function hashPassword(pw) {
  const salt = randomBytes(16);
  const hash = pbkdf2Sync(pw, salt, PBKDF2_ITER, 32, 'sha256');
  return `pbkdf2_sha256$${PBKDF2_ITER}$${salt.toString('base64')}$${hash.toString('base64')}`;
}

function main() {
  const html = readFileSync(new URL('prototype/LOF_CRM_Prototype.html', root), 'utf8');
  const S = runPrototypeSeed(html);
  const masters = ['branches', 'programs', 'fees', 'discounts', 'staff'];
  const lines = ['-- GENERATED by scripts/build-seed.mjs – do not edit by hand', 'PRAGMA defer_foreign_keys = true;'];

  const branchOfIndex = {};
  for (const l of S.leads) branchOfIndex['lead:' + l.id] = l.branch;
  for (const e of S.enr) branchOfIndex['enrollment:' + e.id] = e.branch;
  const branchOf = (t, id) => branchOfIndex[t + ':' + id] ?? null;

  for (const [coll, type] of Object.entries(COLLECTIONS)) {
    if (mastersOnly && !masters.includes(coll)) continue;
    for (const d of S[coll] || []) {
      const c = indexFor(type, d, branchOf);
      lines.push(
        `INSERT OR REPLACE INTO docs (type,id,branch,status,owner,ref1,ref2,at,data,updated_by) VALUES (` +
          [type, d.id, c.branch, c.status, c.owner, c.ref1, c.ref2, c.at, JSON.stringify(d), 'seed'].map(q).join(',') + `);`,
      );
    }
  }

  // Settings – never store integration secrets in configuration documents
  const cfg = structuredClone(S.cfg);
  if (cfg.integ?.moodle) cfg.integ.moodle.token = '';
  const settings = { cfg, perms: S.perms, scope: S.scope, fx: S.fx, hist: S.hist };
  for (const k of SETTINGS_KEYS) lines.push(`INSERT OR REPLACE INTO settings (key,data,updated_by) VALUES (${q(k)},${q(JSON.stringify(settings[k]))},'seed');`);

  // Sequences: next value = max(prototype counter, highest existing number + 1)
  const maxNum = (arr, re) => arr.reduce((m, d) => { const x = String(d.id).match(re); return x ? Math.max(m, +x[1]) : m; }, 0);
  const seqs = {
    lead: Math.max(S.seq.lead, maxNum(S.leads, /^LD-26-(\d+)$/) + 1),
    opp: Math.max(S.seq.opp, maxNum(S.opps, /^OP-26-(\d+)$/) + 1),
    enr: Math.max(S.seq.enr, maxNum(S.enr, /^EN-26-(\d+)$/) + 1),
    pay: maxNum(S.pay, /^PY-26-(\d+)$/) + 1,
    student: Math.max(S.seq.student, maxNum(S.students, /^LOF-26-(\d+)$/) + 1),
    ap: Math.max(S.seq.ap, maxNum(S.approvals, /^AP-26-(\d+)$/) + 1),
    rf: Math.max(S.seq.rf, maxNum(S.refunds, /^RF-26-(\d+)$/) + 1),
    pd: Math.max(S.seq.pd, maxNum(S.discounts, /^PD-(\d+)$/) + 1),
    ms: Math.max(S.seq.ms, maxNum(S.ms, /^MS-(\d+)$/) + 1),
    task: Math.max(S.seq.task, maxNum(S.tasks, /^T-(\d+)$/) + 1),
    call: Math.max(S.seq.call, maxNum(S.calls, /^CL-(\d+)$/) + 1),
    cm: S.seq.cm,
    notif: S.seq.notif,
    audit: S.seq.audit,
    plink: 1,
  };
  for (const b of S.branches) {
    const nums = S.pay.filter((p) => p.branch === b.id).map((p) => +String(p.rc).split('-').pop());
    seqs['rc_' + b.id] = (nums.length ? Math.max(...nums) : 0) + 1;
  }
  if (mastersOnly) for (const k of ['lead', 'opp', 'enr', 'pay', 'student', 'ap', 'rf', 'ms', 'task', 'call']) seqs[k] = 1;
  for (const [k, v] of Object.entries(seqs)) lines.push(`INSERT OR REPLACE INTO sequences (name,value) VALUES (${q(k)},${v});`);

  // Logins. Demo data: the shared demo password. Masters only (production): a random password nobody knows –
  // the System Administrator issues each person a temporary password (Users → Reset password).
  for (const s of S.staff) {
    const pw = mastersOnly ? randomBytes(24).toString('base64url') + 'aA1!' : DEMO_PASSWORD;
    lines.push(`INSERT OR REPLACE INTO staff_auth (staff_id,email,password_hash,must_change) VALUES (${q(s.id)},${q(s.email.toLowerCase())},${q(hashPassword(pw))},1);`);
  }

  const out = new URL('migrations/0002_seed.sql', root);
  writeFileSync(out, lines.join('\n') + '\n');
  console.log(`Wrote ${lines.length} statements to migrations/0002_seed.sql (${mastersOnly ? 'masters only' : 'demo data'}).`);
  console.log(mastersOnly ? "Staff logins have random passwords: create the administrator with scripts/create-admin.mjs, then issue temporary passwords from the CRM." : `Demo login: any staff e-mail (e.g. ${S.staff.find((s) => s.role === "System Administrator").email}) / ${DEMO_PASSWORD}`);
  void ID_FORMAT;
}

if (import.meta.url === `file://${process.argv[1]}`) main();
