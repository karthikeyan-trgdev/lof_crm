// Creates (or updates) a System Administrator login. Prints SQL to apply with wrangler; only the
// password hash is written, never the password itself.
//
//   ADMIN_PASSWORD='…' node scripts/create-admin.mjs --email you@company.com --name "Your Name" > admin.sql
//   npx wrangler d1 execute lof_crm --local  --file admin.sql      # local dev
//   npx wrangler d1 execute lof_crm --remote --file admin.sql      # production
//   rm admin.sql
//
// Options: --id S16 --branch KRM --mobile "+971 …" --must-change (force a new password at first sign-in)
import { pbkdf2Sync, randomBytes } from 'node:crypto';
import { indexFor } from '../src/lib/indexing.ts';

const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
const email = String(arg('email', '')).trim().toLowerCase();
const name = arg('name', 'System Administrator');
const id = arg('id', 'S16');
const branch = arg('branch', 'KRM');
const mobile = arg('mobile', '');
const mustChange = process.argv.includes('--must-change') ? 1 : 0;
const password = process.env.ADMIN_PASSWORD || '';

if (!/^\S+@\S+\.\S+$/.test(email)) { console.error('Give a valid --email'); process.exit(1); }
if (password.length < 10 || !/[A-Za-z]/.test(password) || !/\d/.test(password)) {
  console.error('ADMIN_PASSWORD must have at least 10 characters with letters and numbers'); process.exit(1);
}

const salt = randomBytes(16);
const hash = `pbkdf2_sha256$100000$${salt.toString('base64')}$${pbkdf2Sync(password, salt, 100000, 32, 'sha256').toString('base64')}`;
const staff = {
  id, name, emp: 'LOF-E' + id.replace(/\D/g, '').padStart(3, '0'), role: 'System Administrator', branch, dept: 'Management',
  email, mobile, programs: [], status: 'Active', access: 'Enabled', avail: 'Available', max: 0, leave: null, backup: '',
};
const c = indexFor('staff', staff);
const q = (v) => (v == null ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'");

console.log(`-- System Administrator login for ${email} (generated by scripts/create-admin.mjs)
DELETE FROM staff_auth WHERE email=${q(email)} AND staff_id<>${q(id)};
INSERT INTO docs (type,id,branch,status,owner,ref1,ref2,at,data,updated_by) VALUES ('staff',${q(id)},${q(c.branch)},${q(c.status)},${q(c.owner)},${q(c.ref1)},NULL,NULL,${q(JSON.stringify(staff))},'create-admin')
  ON CONFLICT(type,id) DO UPDATE SET branch=excluded.branch,status=excluded.status,owner=excluded.owner,ref1=excluded.ref1,data=excluded.data,updated_at=strftime('%Y-%m-%dT%H:%M:%fZ','now'),updated_by=excluded.updated_by;
INSERT INTO staff_auth (staff_id,email,password_hash,must_change) VALUES (${q(id)},${q(email)},${q(hash)},${mustChange})
  ON CONFLICT(staff_id) DO UPDATE SET email=excluded.email,password_hash=excluded.password_hash,must_change=excluded.must_change,failed_count=0,locked_until=NULL;`);
